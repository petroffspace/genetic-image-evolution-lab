// worleyAt's 5x5 neighborhood search must equal a brute-force search over
// every feature point (with periodic wrap) for F1, F2-F1 and cell value,
// in all three metrics, at full and partial jitter (the search prunes by
// each cell's jitter box).
func TestWorleyMatchesBruteForce(t *testing.T) {
	rng := rand.New(rand.NewSource(6))
	const cells = 7
	for _, jit := range []float64{1, 0.75, 0.4} {
		pts := cellPoints(phaseSource{seed: 99}, cells, jit)
		for metric := 0; metric < 3; metric++ {
			dist := func(dx, dy float64) float64 {
				dx, dy = math.Abs(dx), math.Abs(dy)
				switch metric {
				case 1:
					return dx + dy
				case 2:
					return math.Max(dx, dy)
				}
				return math.Hypot(dx, dy)
			}
			for i := 0; i < 2000; i++ {
				fx, fy := rng.Float64()*cells, rng.Float64()*cells
				f1, f2, val := math.Inf(1), math.Inf(1), 0.0
				for iy := 0; iy < cells; iy++ {
					for ix := 0; ix < cells; ix++ {
						p := pts[iy*cells+ix]
						for oy := -1; oy <= 1; oy++ { // periodic images of the point
							for ox := -1; ox <= 1; ox++ {
								d := dist(float64(ix+ox*cells)+p[0]-fx, float64(iy+oy*cells)+p[1]-fy)
								if d < f1 {
									f1, f2, val = d, f1, p[2]
								} else if d < f2 {
									f2 = d
								}
							}
						}
					}
				}
				if got := worleyAt(fx, fy, cells, pts, metric, 1, jit); math.Abs(got-f1) > 1e-12 {
					t.Fatalf("metric %d F1 at (%.3f,%.3f): %v, brute force %v", metric, fx, fy, got, f1)
				}
				if got := worleyAt(fx, fy, cells, pts, metric, 2, jit); math.Abs(got-(f2-f1)) > 1e-12 {
					t.Fatalf("metric %d F2-F1 at (%.3f,%.3f): %v, brute force %v", metric, fx, fy, got, f2-f1)
				}
				if got := worleyAt(fx, fy, cells, pts, metric, 3, jit); got != val {
					t.Fatalf("metric %d value at (%.3f,%.3f): %v, brute force %v", metric, fx, fy, got, val)
				}
			}
		}
	}
}

