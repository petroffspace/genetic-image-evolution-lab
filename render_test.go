// Gentle children must stay measurably closer to the parent than wild ones,
// both in their genes and in how far their phase realization moved.
func TestStrengthControlsDistance(t *testing.T) {
	parent := randomGenome(rand.New(rand.NewSource(3)))
	spread := func(strength float64) (dist, phaseMove float64) {
		rng := rand.New(rand.NewSource(11))
		const n = 2000
		for i := 0; i < n; i++ {
			c := breedGenome(parent, nil, rng, strength)
			dist += math.Abs(c.Gamma-parent.Gamma) + math.Abs(c.BandLimit-parent.BandLimit) +
				math.Abs(c.Colorfulness-parent.Colorfulness)
			switch {
			case c.Seed != parent.Seed:
				phaseMove++ // hard jump to a new realization
			case c.phases().blended():
				phaseMove += c.SeedBlend
			}
		}
		return dist / n, phaseMove / n
	}
	gd, gp := spread(gentleStrength)
	nd, np := spread(normalStrength)
	wd, wp := spread(wildStrength)
	if !(gd < nd && nd < wd) {
		t.Errorf("gene distance not ordered gentle < normal < wild: %.3f %.3f %.3f", gd, nd, wd)
	}
	if !(gp < np && np < wp) {
		t.Errorf("phase movement not ordered gentle < normal < wild: %.3f %.3f %.3f", gp, np, wp)
	}
}

