// Modulate scales A by a bounded envelope in [1-Mix, 1+Mix]; an unbounded
// envelope let a few extreme values flatten the normalized image.
func TestLayerModulateBounded(t *testing.T) {
	const n = 256
	g := layeredGenome(2)
	g.Layer.Mix = 0.8
	a := synthChannel(n, n, rand.New(rand.NewSource(g.Seed)), g)
	out := composeLayers(append([]float64(nil), a...), n, g)
	standardize(a)
	for i := range a {
		if math.Abs(a[i]) < 1e-6 {
			continue
		}
		if r := out[i] / a[i]; r < 1-g.Layer.Mix-1e-9 || r > 1+g.Layer.Mix+1e-9 {
			t.Fatalf("modulation ratio %.3f outside [%.1f, %.1f]", r, 1-g.Layer.Mix, 1+g.Layer.Mix)
		}
	}
	f := fieldOf(g)
	var vals []float64
	for y := 0; y < f.height; y++ {
		for x := 0; x < f.width; x++ {
			vals = append(vals, float64(f.lumF[y*f.padW+x]))
		}
	}
	var mean, sq float64
	for _, v := range vals {
		mean += v
	}
	mean /= float64(len(vals))
	for _, v := range vals {
		sq += (v - mean) * (v - mean)
	}
	if sd := math.Sqrt(sq / float64(len(vals))); sd < 0.1 {
		t.Errorf("modulated field nearly flat after normalization (std %.3f)", sd)
	}
}

