// The tile fold maps every sector onto the first. Without mirroring it is
// invariant under rotation by one sector angle, all the way around. With
// mirroring it is invariant under reflection across a sector edge (checked
// within the first two sectors, which odd folds' wrap-around seam at angle
// 0 never touches). The radius is always preserved.
func TestTileFoldGeometry(t *testing.T) {
	rng := rand.New(rand.NewSource(2))
	for _, k := range []int{2, 3, 4, 6, 7} {
		sec := 2 * math.Pi / float64(k)
		for _, mirror := range []bool{false, true} {
			f := newTileFold(Genome{SymmetryFold: k, SymmetryMirror: mirror}, fieldTile)
			at := func(r, a float64) (float64, float64) { return f.apply(f.c+r*math.Cos(a), f.c+r*math.Sin(a)) }
			for i := 0; i < 300; i++ {
				r := 1 + rng.Float64()*600
				var a, a2 float64
				if mirror {
					a = 1e-3 + rng.Float64()*(2*sec-2e-3)
					a2 = 2*sec - a // reflection across the edge at angle sec
				} else {
					a = rng.Float64() * 2 * math.Pi
					a2 = a + sec
				}
				pu, pv := at(r, a)
				qu, qv := at(r, a2)
				if math.Hypot(pu-qu, pv-qv) > 1e-6 {
					t.Fatalf("k=%d mirror=%v: angles %.3f and %.3f fold to (%.3f,%.3f) vs (%.3f,%.3f)",
						k, mirror, a, a2, pu, pv, qu, qv)
				}
				if math.Abs(math.Hypot(pu-f.c, pv-f.c)-r) > 1e-6 {
					t.Fatalf("k=%d: fold changed the radius", k)
				}
			}
		}
	}
}

