func TestFrozenRenderVersionsUnchanged(t *testing.T) {
	for _, set := range []struct {
		version  int
		fixtures []struct{ genome, preview, frame string }
	}{{0, legacyFixtures}, {1, v1Fixtures}, {2, v2Fixtures}, {3, v3Fixtures}, {4, v4Fixtures}, {5, v5Fixtures}, {6, v6Fixtures}} {
		for i, fx := range set.fixtures {
			var g Genome
			if err := json.Unmarshal([]byte(fx.genome), &g); err != nil {
				t.Fatalf("v%d fixture %d: %v", set.version, i, err)
			}
			if g.RenderVersion != set.version {
				t.Fatalf("v%d fixture %d has render_version %d", set.version, i, g.RenderVersion)
			}
			// renderGridPreview is what the grid shows (plain renderClean
			// before version 4, supersampled from version 4 on).
			if got := fmt.Sprintf("%x", sha256.Sum256(renderGridPreview(g).Pix)); got != fx.preview {
				t.Errorf("v%d fixture %d: preview changed\n got %s\nwant %s", set.version, i, got, fx.preview)
			}
			if got := fmt.Sprintf("%x", sha256.Sum256(renderExactFramed(g, 320, 180).Pix)); got != fx.frame {
				t.Errorf("v%d fixture %d: 320x180 frame changed\n got %s\nwant %s", set.version, i, got, fx.frame)
			}
		}
	}
}

// overlapCorr renders the luminance field of g at w x h1 and w x h2
// (h2 < h1, same long side, so the tile is sampled at the same scale)
// and correlates the vertically centered overlap.
func overlapCorr(g Genome, w, h1, h2 int) float64 {
	a := spectralField(w, h1, rand.New(rand.NewSource(g.Seed)), g)
	b := spectralField(w, h2, rand.New(rand.NewSource(g.Seed)), g)
	off := (h1 - h2) / 2
	var xs, ys []float64
	for y := 0; y < h2; y++ {
		for x := 0; x < w; x++ {
			xs = append(xs, float64(a.lum[(y+off)*a.padW+x]))
			ys = append(ys, float64(b.lum[y*b.padW+x]))
		}
	}
	return pearsonCorr(xs, ys)
}

// v1 domain warp is isotropic and centered: a 16:9 frame shows the same
// marble as the middle band of the 4:3 preview. Legacy warp stretched
// with the aspect ratio, so the same check fails for it (~0.78). A small
// warp keeps edge clamping (offsets reaching past the shorter canvas)
// from dominating the comparison.
func TestDomainWarpAspectConsistent(t *testing.T) {
	g := Genome{Seed: 42, Exponent: 2.5, BandLimit: 0.6, AxisStretch: 1,
		Gamma: 1, Colorfulness: 1, ConeWidth: 1, DomainWarp: 0.05,
		RenderVersion: renderVersion}
	if c := overlapCorr(g, 320, 240, 180); c < 0.99 {
		t.Errorf("v%d warp: 4:3 vs 16:9 overlap correlation %.4f, want >= 0.99", renderVersion, c)
	}
	g.RenderVersion = 0
	if c := overlapCorr(g, 320, 240, 180); c > 0.9 {
		t.Errorf("legacy warp unexpectedly aspect-consistent (corr %.4f): test lost sensitivity", c)
	}
}

func TestSlotStrengths(t *testing.T) {
	count := func(s []float64, v float64) (n int) {
		for _, x := range s {
			if x == v {
				n++
			}
		}
		return
	}
	full := slotStrengths(8)
	if g, n, w := count(full, gentleStrength), count(full, normalStrength), count(full, wildStrength); g != 3 || n != 3 || w != 2 {
		t.Errorf("8 slots: %d gentle / %d normal / %d wild, want 3/3/2", g, n, w)
	}
	for i := 1; i < len(full); i++ {
		if full[i] < full[i-1] {
			t.Errorf("strengths not ascending in grid order: %v", full)
		}
	}
	for n := 0; n <= 8; n++ {
		if got := len(slotStrengths(n)); got != n {
			t.Errorf("slotStrengths(%d) has %d entries", n, got)
		}
	}
	if s := slotStrengths(1); s[0] != normalStrength {
		t.Errorf("single free slot got strength %v, want normal", s[0])
	}
}

