// scaleCorr renders g's structure field at 256x192 and at 512x384, box-
// averages the large one 2x2, and correlates: a field defined in tile
// space looks the same at both resolutions.
func scaleCorr(g Genome) float64 {
	small := spectralField(256, 192, rand.New(rand.NewSource(g.Seed)), g)
	big := spectralField(512, 384, rand.New(rand.NewSource(g.Seed)), g)
	var a, b []float64
	for y := 0; y < 192; y++ {
		for x := 0; x < 256; x++ {
			a = append(a, float64(small.lumF[y*small.padW+x]))
			var s float64
			for dy := 0; dy < 2; dy++ {
				for dx := 0; dx < 2; dx++ {
					s += float64(big.lumF[(2*y+dy)*big.padW+2*x+dx])
				}
			}
			b = append(b, s/4)
		}
	}
	return pearsonCorr(a, b)
}

