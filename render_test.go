// idealGreen is the exact, never-quantized green channel (0..255) of a
// genome restricted to the plain pipeline (cosine palette, no transform,
// relief, chroma, warp or symmetry, colorfulness 1).
func idealGreen(g Genome, w, h int) []float64 {
	f := spectralField(w, h, rand.New(rand.NewSource(g.Seed)), g)
	out := make([]float64, w*h)
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			t := math.Pow(float64(f.lumF[y*f.padW+x]), g.Gamma)
			out[y*w+x] = clampF(g.PalA[1]+g.PalB[1]*math.Cos(2*math.Pi*(g.PalC[1]*t+g.PalD[1])), 0, 1) * 255
		}
	}
	return out
}

// bandingPeak is the largest low-frequency (13x13 box-blurred, mean
// removed) deviation of img's green channel from the ideal, in 8-bit
// levels. Blurring cancels dither, which is high-frequency by design;
// what survives is banding: wide plateaus off the true value.
func bandingPeak(img *image.RGBA, ideal []float64, w, h int) float64 {
	const R = 6
	var mean float64
	for i := range ideal {
		mean += float64(img.Pix[i*4+1]) - ideal[i]
	}
	mean /= float64(len(ideal))
	S := make([]float64, (w+1)*(h+1))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			e := float64(img.Pix[(y*w+x)*4+1]) - ideal[y*w+x] - mean
			S[(y+1)*(w+1)+x+1] = e + S[y*(w+1)+x+1] + S[(y+1)*(w+1)+x] - S[y*(w+1)+x]
		}
	}
	var peak float64
	for y := R; y < h-R-1; y++ {
		for x := R; x < w-R-1; x++ {
			s := S[(y+R+1)*(w+1)+x+R+1] - S[(y-R)*(w+1)+x+R+1] - S[(y+R+1)*(w+1)+x-R] + S[(y-R)*(w+1)+x-R]
			peak = math.Max(peak, math.Abs(s/float64((2*R+1)*(2*R+1))))
		}
	}
	return peak
}

