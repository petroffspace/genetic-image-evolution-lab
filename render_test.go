func meanAbsDiff(a, b *image.RGBA) float64 {
	var s float64
	for i := 0; i < len(a.Pix); i += 4 {
		for c := 0; c < 3; c++ {
			s += math.Abs(float64(a.Pix[i+c]) - float64(b.Pix[i+c]))
		}
	}
	return s / float64(len(a.Pix)/4*3)
}

// runAnimation drives the real animation handler into a temp folder and
// returns the status code, error message and decoded frames.
func runAnimation(t *testing.T, body map[string]interface{}) (int, string, []*image.RGBA) {
	body["dir"] = t.TempDir()
	b, _ := json.Marshal(body)
	rec := httptest.NewRecorder()
	handleRenderAnimation(rec, httptest.NewRequest("POST", "/api/render-animation", bytes.NewReader(b)))
	var resp map[string]interface{}
	json.Unmarshal(rec.Body.Bytes(), &resp)
	if rec.Code != 200 {
		return rec.Code, fmt.Sprint(resp["error"]), nil
	}
	files, _ := filepath.Glob(filepath.Join(fmt.Sprint(resp["output_dir"]), "frame_*.png"))
	sort.Strings(files)
	var imgs []*image.RGBA
	for _, p := range files {
		f, err := os.Open(p)
		if err != nil {
			t.Fatal(err)
		}
		im, err := png.Decode(f)
		f.Close()
		if err != nil {
			t.Fatal(err)
		}
		rgba := image.NewRGBA(im.Bounds())
		draw.Draw(rgba, rgba.Bounds(), im, image.Point{}, draw.Src)
		imgs = append(imgs, rgba)
	}
	return 200, "", imgs
}

func steps(imgs []*image.RGBA) []float64 {
	var st []float64
	for i := 0; i+1 < len(imgs); i++ {
		st = append(st, meanAbsDiff(imgs[i], imgs[i+1]))
	}
	return st
}

func median(v []float64) float64 {
	c := append([]float64(nil), v...)
	sort.Float64s(c)
	return c[len(c)/2]
}

// The timeline: a single cell loops seamlessly; multi-cell runs hold each
// cell (live motion), morph to the next, and never jump at a hold /
// transition boundary in any mode; frame counts follow the timeline.
func TestTimelineAnimation(t *testing.T) {
	state = NewAppState(t.TempDir())
	r := rand.New(rand.NewSource(5))
	for i := range state.cells {
		g := randomGenome(r)
		g.RD.Mode = 0
		state.cells[i].Genome = g
	}
	motion := map[string]interface{}{"flow": 1.0, "drift": 1, "drift_dir": 1, "color": 1}
	base := func(cells []int, hold, trans int, mode string) map[string]interface{} {
		return map[string]interface{}{"source_cells": cells, "hold_frames": hold, "transition_frames": trans,
			"fps": 24, "width": 160, "height": 90, "easing": "inoutcubic", "mode": mode, "motion": motion}
	}

	code, msg, imgs := runAnimation(t, base([]int{3}, 12, 0, "params"))
	if code != 200 || len(imgs) != 12 {
		t.Fatalf("single cell: code %d (%s), %d frames, want 12", code, msg, len(imgs))
	}
	if st, wrap := steps(imgs), meanAbsDiff(imgs[11], imgs[0]); wrap > 1.6*median(st) {
		t.Errorf("single-cell loop not seamless: wrap step %.1f vs median step %.1f", wrap, median(st))
	}

	const hold, trans = 6, 5
	for _, mode := range []string{"params", "crossfade", "morph"} {
		code, msg, imgs := runAnimation(t, base([]int{0, 1, 2}, hold, trans, mode))
		if want := 3*hold + 2*trans; code != 200 || len(imgs) != want {
			t.Fatalf("%s: code %d (%s), %d frames, want %d", mode, code, msg, len(imgs), want)
		}
		st := steps(imgs)
		for _, b := range []int{hold - 1, hold + trans - 1, 2*hold + trans - 1, 2*hold + 2*trans - 1} {
			if st[b] > 1.6*median(st) {
				t.Errorf("%s: jump at boundary step %d: %.1f vs median %.1f", mode, b, st[b], median(st))
			}
		}
	}

	// Without motion, holds are exact stills and the first hold frame is
	// the cell's normal render.
	still := base([]int{0, 1}, 5, 4, "crossfade")
	still["motion"] = map[string]interface{}{}
	_, _, imgs = runAnimation(t, still)
	for i := 1; i < 5; i++ {
		if meanAbsDiff(imgs[0], imgs[i]) != 0 {
			t.Fatalf("still hold frame %d differs from frame 0", i)
		}
	}
	if d := meanAbsDiff(imgs[0], renderExactFramed(state.cells[0].Genome, 160, 90)); d != 0 {
		t.Errorf("still hold differs from the cell's normal render by %.3f", d)
	}

	if code, _, _ := runAnimation(t, map[string]interface{}{"source_cells": []int{3}, "frames": 30,
		"fps": 24, "width": 160, "height": 90, "mode": "params"}); code != 400 {
		t.Errorf("single cell without timeline settings: code %d, want 400", code)
	}
}

