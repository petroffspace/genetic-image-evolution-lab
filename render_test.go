// seamTolerance is the worst-pixel error allowed between the interpolated
// and exact folded resample, as a fraction of the field range. Measured:
// 3-6% with seam detection, 10-16% without it on folds that have a
// discontinuous seam (non-mirrored, or odd mirrored at angle 0).
const seamTolerance = 0.08

// The folded resample interpolates transformed pixel centers and falls
// back to the exact per-tap footprint on fold seams; it must agree with
// running the exact footprint everywhere.
func TestFoldInterpolationMatchesExact(t *testing.T) {
	const tile = 1024
	src := synthChannel(tile, tile, rand.New(rand.NewSource(5)),
		Genome{Seed: 5, Exponent: 2.2, BandLimit: 0.8, AxisStretch: 1, ConeWidth: 1})
	ft := float64(tile)
	samp := func(u, v float64) float64 { return samplePeriodic(src, tile, u, v) }
	for _, c := range []struct {
		fold   int
		mirror bool
		warp   float64
	}{{3, false, 0}, {5, true, 0}, {6, false, 0.3}, {4, true, 0.3}} {
		g := Genome{Seed: 9, SymmetryFold: c.fold, SymmetryMirror: c.mirror, DomainWarp: c.warp,
			WarpScale: 3, WarpNest: 2, RenderVersion: renderVersion}
		fold, warp := newTileFold(g, tile), newTileWarp(g, tile)
		const w, h = 300, 220
		padW, padH := nextPow2(w), nextPow2(h)
		fast := resampleTile(src, tile, tile, w, h, padW, padH, warp, fold)
		xf := fold.apply
		if warp != nil {
			xf = func(u, v float64) (float64, float64) { return warp.apply(fold.apply(u, v)) }
		}
		wpp := ft / w
		var a, b []float64
		var worst float64
		lo, hi := minMax(src)
		for y := 0; y < h; y++ {
			for x := 0; x < w; x++ {
				ox := ft/2 + (float64(x)+0.5-float64(w)/2)*wpp
				oy := ft/2 + (float64(y)+0.5-float64(h)/2)*wpp
				e := footprint(xf, samp, ox, oy, wpp)
				a, b = append(a, e), append(b, fast[y*padW+x])
				worst = math.Max(worst, math.Abs(e-fast[y*padW+x])/(hi-lo))
			}
		}
		if corr := pearsonCorr(a, b); corr < 0.995 {
			t.Errorf("fold %d mirror %v warp %.1f: interpolated vs exact corr %.4f", c.fold, c.mirror, c.warp, corr)
		}
		// Seams are thin lines that a whole-image correlation cannot see;
		// blending coordinates across one shows up as a worst-pixel error.
		if worst > seamTolerance {
			t.Errorf("fold %d mirror %v warp %.1f: worst pixel off by %.1f%% of range (seam blending?)", c.fold, c.mirror, c.warp, 100*worst)
		}
	}
}

