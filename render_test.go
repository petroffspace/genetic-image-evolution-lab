// edgeCoherenceExcess is how much more directional (5x5 structure-tensor
// coherence) the outer band of an image is than its interior. Clamped
// symmetry sampling stretched border pixels into radial streaks, which
// shows up as a coherent edge band.
func edgeCoherenceExcess(img *image.RGBA) float64 {
	w, h := img.Bounds().Dx(), img.Bounds().Dy()
	l := lumaOf(img)
	gx, gy := make([]float64, w*h), make([]float64, w*h)
	for y := 1; y < h-1; y++ {
		for x := 1; x < w-1; x++ {
			gx[y*w+x] = l[y*w+x+1] - l[y*w+x-1]
			gy[y*w+x] = l[(y+1)*w+x] - l[(y-1)*w+x]
		}
	}
	b := w / 12
	var sum [2]float64
	var n [2]int
	for y := 3; y < h-3; y++ {
		for x := 3; x < w-3; x++ {
			var a, bb, c float64
			for dy := -2; dy <= 2; dy++ {
				for dx := -2; dx <= 2; dx++ {
					i := (y+dy)*w + x + dx
					a, bb, c = a+gx[i]*gx[i], bb+gy[i]*gy[i], c+gx[i]*gy[i]
				}
			}
			if a+bb < 1e-9 {
				continue
			}
			k := 1
			if x < b || y < b || x >= w-b || y >= h-b {
				k = 0
			}
			sum[k] += math.Sqrt((a-bb)*(a-bb)+4*c*c) / (a + bb)
			n[k]++
		}
	}
	return sum[0]/float64(n[0]) - sum[1]/float64(n[1])
}

