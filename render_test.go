// dominantWavelength is the wavelength (in tile units, tile = 1) of the
// radially averaged power spectrum's peak of an n x n periodic field,
// searched from minCycles cycles per tile upward (below that the
// spectrum reflects which regions the pattern covers, not the pattern).
func dominantWavelength(f []float64, n, minCycles int) float64 {
	data := make([][]complex128, n)
	for y := range data {
		data[y] = make([]complex128, n)
		for x := range data[y] {
			data[y][x] = complex(f[y*n+x], 0)
		}
	}
	fft2d(data, false)
	power := make([]float64, n/2)
	for y := 0; y < n; y++ {
		for x := 0; x < n; x++ {
			r := int(math.Round(math.Hypot(freqCoord(x, n), freqCoord(y, n))))
			if r > 1 && r < n/2 {
				p := real(data[y][x])*real(data[y][x]) + imag(data[y][x])*imag(data[y][x])
				power[r] += p
			}
		}
	}
	best := minCycles
	for r := minCycles; r < n/2; r++ {
		if power[r] > power[best] {
			best = r
		}
	}
	return 1 / float64(best)
}

