func lumaOf(img *image.RGBA) []float64 {
	out := make([]float64, 0, len(img.Pix)/4)
	for i := 0; i < len(img.Pix); i += 4 {
		out = append(out, 0.2126*float64(img.Pix[i])+0.7152*float64(img.Pix[i+1])+0.0722*float64(img.Pix[i+2]))
	}
	return out
}

