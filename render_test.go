// Streaks are computed on the periodic tile in tile units: seamless and
// identical at every resolution, for both flows and stroke widths.
func TestLicSeamlessAndResolutionInvariant(t *testing.T) {
	// Seam check: the mean jump across the tile edge (column n-1 -> 0),
	// averaged over seeds, must look like any interior column's. Only
	// same-parity columns compare: the 2x bilinear upsample makes pairs
	// inside one LIC cell jump ~1.5x more than pairs straddling a node, and
	// the edge pair is an inside-cell pair. Single-seed column jumps vary a
	// lot, hence the averaging and a z-score bound.
	const n, seeds = 512, 8
	col := make([]float64, n)
	for k := 0; k < seeds; k++ {
		g := licGenome(2, 1) // swirl flow: no structure field needed
		g.Seed = int64(100 + k)
		lic := licTile(nil, n, g)
		for x := 0; x < n; x++ {
			for y := 0; y < n; y++ {
				col[x] += math.Abs(lic[y*n+x]-lic[y*n+(x+n-1)%n]) / (n * seeds)
			}
		}
	}
	var mean, sd float64
	for x := 2; x < n; x += 2 {
		mean += col[x] / (n/2 - 1)
	}
	for x := 2; x < n; x += 2 {
		sd += (col[x] - mean) * (col[x] - mean) / (n/2 - 1)
	}
	if z := (col[0] - mean) / math.Sqrt(sd); z > 3 {
		t.Errorf("tile seam jump %.3f vs interior %.3f (z=%.1f): not periodic", col[0], mean, z)
	}
	for mode := 1; mode <= 2; mode++ {
		for _, width := range []int{0, 2} {
			if c := scaleCorr(licGenome(mode, width)); c < 0.995 {
				t.Errorf("LIC mode %d width %d: 256 vs 512 field correlation %.4f, want >= 0.995", mode, width, c)
			}
		}
	}
}

